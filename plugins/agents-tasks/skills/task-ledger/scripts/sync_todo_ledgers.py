#!/usr/bin/env python3
"""Regenerate task ledgers and generated area status blocks from task files.

Vendored under the `task-ledger` skill; invoked via `at ledger sync` / `at ledger
check` / `at ledger rotate-log <TASK-ID>` (see `plugins/agents-tasks/bin/at-ledger`).
The behavior, CLI flags, ``--check`` strict/permissive semantics, output text, and
marker-delimited generated blocks are preserved from the historical shell
implementation; the port additionally fixes two long-standing defects by
construction:

- Titles are rendered verbatim: the old shell pipeline ran generated rows
  through ``printf '%b'``, which expanded backslash escapes (``\\t``, ``\\n``,
  Windows paths) inside task titles and corrupted the ledgers.
- Table metadata is parsed with the shared escape-aware splitter in
  ``mdtables.py`` (the same one ``check_repos_config.sh`` uses), so an
  escaped pipe (``\\|``) in a cell is understood instead of mis-split.

Sources of truth:
  docs/tasks_manager/_areas.md
  docs/tasks_manager/_roadmap.md
  docs/tasks_manager/_todos/*.md
  docs/tasks_manager/_todos_archived/*.md

Generated outputs:
  docs/tasks_manager/_active.md
  docs/tasks_manager/_done.md
  docs/areas/_overview.md
  marker-delimited blocks in docs/areas/<slug>.md
"""

