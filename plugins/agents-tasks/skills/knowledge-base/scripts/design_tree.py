#!/usr/bin/env python3
"""Generate and check the design trees under `docs/resources/<area>/design/`.

Usage:
  design_tree.py --root <repo>            rewrite the generated blocks (`at design sync`)
  design_tree.py --root <repo> --check    report problems, write nothing (`at design check`)

The format is defined in the knowledge-base skill, `references/design-convention.md`.
Exit codes: 0 ok (warnings allowed), 1 errors, 2 usage. Python 3 stdlib only.
"""

from __future__ import annotations

import datetime
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "task-ledger" / "scripts"))
from mdtables import is_separator, metadata_pairs, split_table_row  # noqa: E402

STATUSES = ("draft", "accepted", "implemented", "superseded")
MAX_LINES = 500
MAX_DEPTH = 3
STALE_DAYS = 180
DECISION_COLUMNS = ["ID", "Date", "Decision", "Why", "Source", "Supersedes", "Status"]
INDEX_BEGIN, INDEX_END = "<!-- BEGIN generated-design-index -->", "<!-- END generated-design-index -->"
TASKS_BEGIN, TASKS_END = "<!-- BEGIN generated-design-tasks -->", "<!-- END generated-design-tasks -->"
NOTE = "_Generated by `at design sync`. Do not edit this block by hand._"

TASK_ID = re.compile(r"\b[A-Z][A-Z0-9]*-\d{2,}\b")
LINK = re.compile(r"\]\(([^)\s]+)\)")
DESIGN_REF = re.compile(r"docs/resources/[^\s,;`)|]+?/design(?:/[^\s,;`)|]*)?")


def frontmatter(text: str) -> dict | None:
    """Parse the small YAML subset a leaf uses: scalars, one-level maps, lists."""
    lines = text.split("\n")
    if not lines or lines[0].strip() != "---":
        return None
    data: dict = {}
    key = None
    for line in lines[1:]:
        if line.strip() == "---":
            return data
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if line[0] not in " \t":
            name, _, value = line.partition(":")
            key, value = name.strip(), value.strip()
            if value.startswith("[") and value.endswith("]"):
                data[key] = [item.strip().strip("'\"") for item in value[1:-1].split(",") if item.strip()]
            else:
                data[key] = value.strip("'\"") if value else None
        elif key is not None:
            item = line.strip()
            if item.startswith("- "):
                if not isinstance(data[key], list):
                    data[key] = []
                data[key].append(item[2:].strip().strip("'\""))
            elif ":" in item:
                if not isinstance(data[key], dict):
                    data[key] = {}
                name, _, value = item.partition(":")
                data[key][name.strip()] = value.strip().strip("'\"")
    return None  # no closing marker


def prose(text: str) -> str:
    """Drop fenced blocks and inline code, so links and IDs inside examples are ignored."""
    text = re.sub(r"^(```|~~~).*?^\1[^\n]*$", "", text, flags=re.S | re.M)
    return re.sub(r"`[^`\n]*`", "", text)


def section(text: str, title: str) -> str | None:
    match = re.search(rf"^## {re.escape(title)}[ \t]*\n(.*?)(?=^## |\Z)", text, flags=re.S | re.M)
    return match.group(1) if match else None


def replace_block(text: str, begin: str, end: str, body: str) -> str:
    start, stop = text.find(begin), text.find(end)
    return text[:start] + begin + "\n" + NOTE + "\n\n" + body + text[stop:]


class Tree:
    def __init__(self, repo: Path, check: bool) -> None:
        self.repo, self.check = repo, check
        self.errors: list[str] = []
        self.warnings: list[str] = []
        self.written: list[str] = []
        self.meta: dict[Path, dict] = {}
        self.text: dict[Path, str] = {}
        self.open_refs: dict[Path, list[tuple[str, str]]] = {}  # design path -> [(task id, title)]
        self.open_tasks: set[str] = set()
        self.known_tasks: set[str] = set()

    def rel(self, path: Path) -> str:
        return path.relative_to(self.repo).as_posix()

    def read(self, path: Path) -> str:
        if path not in self.text:
            self.text[path] = path.read_text(encoding="utf-8")
        return self.text[path]

    # ------------------------------------------------------------------ tasks
    def load_tasks(self) -> None:
        manager = self.repo / "docs" / "tasks_manager"
        for folder, is_open in (("_todos", True), ("_todos_archived", False)):
            for path in sorted((manager / folder).glob("*.md")):
                lines = path.read_text(encoding="utf-8").split("\n")
                pairs = dict(reversed(metadata_pairs(lines)))  # first occurrence wins
                task = pairs.get("Task ID") or path.name.split("_")[0].rsplit("-", 1)[0]
                self.known_tasks.add(task)
                if not is_open:
                    continue
                self.open_tasks.add(task)
                title = next((line[3:].strip() for line in lines if line.startswith("## ")), "")
                for ref in DESIGN_REF.findall(pairs.get("Spec refs", "")):
                    target = self.repo / ref.split("#")[0].rstrip("/.")
                    if not target.exists():
                        self.errors.append(f"task {task}: Spec refs names {ref}, which does not exist")
                        continue
                    self.open_refs.setdefault(target, []).append((task, title))

    # ----------------------------------------------------------------- leaves
    @staticmethod
    def kind(path: Path) -> str:
        if path.name == "README.md":
            return "index"
        if path.name.startswith("_"):
            return "meta"
        return "reference" if path.name.endswith(".reference.md") else "leaf"

    def check_file(self, root: Path, path: Path) -> None:
        rel, kind, text = self.rel(path), self.kind(path), self.read(path)
        for target in LINK.findall(prose(text)):
            if re.match(r"[a-z][a-z0-9+.-]*:|#", target):
                continue
            if not (path.parent / target.split("#")[0]).exists():
                self.errors.append(f"{rel}: link target {target} does not exist")
        if kind in ("index", "meta"):
            return
        if len(path.relative_to(root).parts) - 1 > MAX_DEPTH:
            self.errors.append(f"{rel}: deeper than {MAX_DEPTH} folder levels under design/")
        meta = frontmatter(text)
        if meta is None:
            self.errors.append(f"{rel}: no frontmatter block")
            return
        self.meta[path] = meta
        if not meta.get("summary"):
            self.errors.append(f"{rel}: frontmatter has no summary")
        if kind == "reference":
            return
        status = meta.get("status")
        if status not in STATUSES:
            self.errors.append(f"{rel}: status is {status!r}; use one of {', '.join(STATUSES)}")
        lines = text.count("\n")
        if lines > MAX_LINES:
            self.errors.append(f"{rel}: {lines} lines; split a leaf at {MAX_LINES}")
        if status == "implemented":
            verified = meta.get("verified")
            stamp = verified.get("date") if isinstance(verified, dict) else None
            try:
                age = (datetime.date.today() - datetime.date.fromisoformat(stamp or "")).days
            except ValueError:
                self.errors.append(f"{rel}: an implemented leaf needs verified.date as YYYY-MM-DD")
            else:
                if age > STALE_DAYS:
                    self.warnings.append(f"{rel}: last verified {stamp}, more than {STALE_DAYS} days ago")
        self.check_decisions(rel, text)
        self.check_pending(path, rel, text)

    def check_decisions(self, rel: str, text: str) -> None:
        body = section(text, "Decisions")
        if body is None:
            return
        rows = [split_table_row(line) for line in body.split("\n") if line.startswith("|")]
        rows = [row for row in rows if not is_separator(row)]
        if not rows:
            return
        if rows[0] != DECISION_COLUMNS:
            self.errors.append(f"{rel}: Decisions columns must be {' | '.join(DECISION_COLUMNS)}")
            return
        by_id: dict[str, list[str]] = {}
        for row in rows[1:]:
            if len(row) != len(DECISION_COLUMNS):
                self.errors.append(f"{rel}: Decisions row {row[0] if row else '?'} has {len(row)} cells, not 7")
                continue
            if not re.fullmatch(r"D-\d{2,}", row[0]):
                self.errors.append(f"{rel}: decision ID {row[0]!r} is not D-NN")
            elif row[0] in by_id:
                self.errors.append(f"{rel}: decision ID {row[0]} is used twice")
            by_id[row[0]] = row
        for ident, row in by_id.items():
            date, supersedes, status = row[1], row[5], row[6]
            if date != "not recorded" and not re.fullmatch(r"\d{4}-\d{2}-\d{2}", date):
                self.errors.append(f"{rel}: {ident} date {date!r} is neither YYYY-MM-DD nor 'not recorded'")
            replaced_by = re.fullmatch(r"superseded by (D-\d{2,})", status)
            if status != "active" and not replaced_by:
                self.errors.append(f"{rel}: {ident} status {status!r} is neither 'active' nor 'superseded by D-NN'")
            if replaced_by and by_id.get(replaced_by.group(1), [""] * 7)[5] != ident:
                self.errors.append(f"{rel}: {ident} is superseded by {replaced_by.group(1)}, "
                                   f"whose Supersedes cell does not name {ident}")
            if re.fullmatch(r"D-\d{2,}", supersedes):
                old = by_id.get(supersedes)
                if old is None:
                    self.errors.append(f"{rel}: {ident} supersedes {supersedes}, which is not in the table")
                elif old[6] != f"superseded by {ident}":
                    self.errors.append(f"{rel}: {ident} supersedes {supersedes}, "
                                       f"whose Status is not 'superseded by {ident}'")
            elif supersedes not in ("—", "-", ""):
                self.errors.append(f"{rel}: {ident} Supersedes cell {supersedes!r} is neither D-NN nor a dash")

    def check_pending(self, path: Path, rel: str, text: str) -> None:
        pending = section(text, "Pending changes") or ""
        named = set(TASK_ID.findall(pending))
        for task in sorted(named & self.known_tasks - self.open_tasks):
            self.warnings.append(f"{rel}: Pending changes names {task}, which is closed")
        for task, _ in self.open_refs.get(path, []):
            if task not in named:
                self.warnings.append(f"{rel}: open task {task} names this leaf in Spec refs; "
                                     f"list it under Pending changes")

    # ---------------------------------------------------------------- indexes
    def summary_of(self, readme: Path) -> str:
        """First sentence of the first prose paragraph of a folder README."""
        para: list[str] = []
        for line in self.read(readme).split("\n"):
            line = line.strip()
            if line and not line.startswith(("#", ">", "<!--", "|", "_Generated")):
                para.append(line)
            elif para:
                break
        return re.split(r"(?<=[.!?])\s", " ".join(para), maxsplit=1)[0]

    def leaves_under(self, folder: Path) -> list[Path]:
        return sorted(p for p in folder.rglob("*.md") if self.kind(p) == "leaf")

    def render_index(self, readme: Path) -> str:
        folder = readme.parent
        rows = []
        for path in sorted(folder.iterdir()):
            if path.is_dir() and (path / "README.md").exists():
                counts: dict[str, int] = {}
                for leaf in self.leaves_under(path):
                    status = self.meta.get(leaf, {}).get("status") or "unknown"
                    counts[status] = counts.get(status, 0) + 1
                state = ", ".join(f"{n} {s}" for s, n in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])))
                rows.append((f"[`{path.name}/`]({path.name}/README.md)", self.summary_of(path / "README.md"),
                             state or "empty"))
            elif path.is_dir():
                for leaf in self.leaves_under(path):
                    name = leaf.relative_to(folder).as_posix()
                    meta = self.meta.get(leaf, {})
                    rows.append((f"[`{name}`]({name})", meta.get("summary") or "", meta.get("status") or ""))
            elif self.kind(path) == "leaf":
                meta = self.meta.get(path, {})
                rows.append((f"[`{path.name}`]({path.name})", meta.get("summary") or "", meta.get("status") or ""))
        lines = ["| Entry | Summary | Status |", "|---|---|---|"]
        lines += [f"| {a} | {b.replace('|', chr(92) + '|')} | {c} |" for a, b, c in rows]
        return "\n".join(lines) + "\n"

    def render_tasks(self, readme: Path) -> str:
        folder = readme.parent
        found: dict[str, tuple[str, set[str]]] = {}
        for target, tasks in self.open_refs.items():
            if target != folder and folder not in target.parents:
                continue
            name = "this module" if target in (folder, readme) else f"`{target.relative_to(folder).as_posix()}`"
            for task, title in tasks:
                found.setdefault(task, (title, set()))[1].add(name)
        lines = ["| Task | Title | Changes |", "|---|---|---|"]
        for task in sorted(found):
            title, names = found[task]
            lines.append(f"| {task} | {title.replace('|', chr(92) + '|')} | {', '.join(sorted(names))} |")
        if not found:
            lines.append("| — | No open task names this module in `Spec refs`. | — |")
        return "\n".join(lines) + "\n"

    def index(self, root: Path, readme: Path) -> None:
        rel, text = self.rel(readme), self.read(readme)
        updated = text
        for begin, end, render in ((INDEX_BEGIN, INDEX_END, self.render_index),
                                   (TASKS_BEGIN, TASKS_END, self.render_tasks)):
            if (begin in text) != (end in text) or text.find(end) < text.find(begin):
                self.errors.append(f"{rel}: {begin} and {end} must both be present, in that order")
                return
            if begin in text:
                updated = replace_block(updated, begin, end, render(readme))
        if updated != text:
            if self.check:
                self.errors.append(f"{rel}: generated block is stale; run `at design sync`")
            else:
                readme.write_text(updated, encoding="utf-8")
                self.written.append(rel)
        if INDEX_BEGIN in text:
            return
        linked = {(readme.parent / t.split("#")[0]).resolve() for t in LINK.findall(prose(text))
                  if not re.match(r"[a-z][a-z0-9+.-]*:|#", t)}
        for leaf in self.leaves_under(readme.parent):
            nearest = next(p for p in leaf.parents if (p / "README.md").exists())
            if nearest == readme.parent and leaf.resolve() not in linked:
                self.errors.append(f"{rel}: does not link to {leaf.relative_to(readme.parent).as_posix()}; "
                                   f"add the link or a {INDEX_BEGIN} block")

    # -------------------------------------------------------------------- run
    def run(self) -> int:
        roots = sorted(p for p in (self.repo / "docs" / "resources").glob("*/design") if p.is_dir())
        if not roots:
            print("design: no docs/resources/<area>/design/ tree in this repository")
            return 0
        self.load_tasks()
        for root in roots:
            if not (root / "README.md").exists():
                self.errors.append(f"{self.rel(root)}: no README.md")
            files = sorted(root.rglob("*.md"))
            for path in files:
                self.check_file(root, path)
            for path in files:
                if path.name == "README.md":
                    self.index(root, path)
        for line in self.warnings:
            print(f"WARNING: {line}")
        for line in self.errors:
            print(f"ERROR: {line}")
        for rel in self.written:
            print(f"updated {rel}")
        leaves = sum(1 for p in self.meta if self.kind(p) == "leaf")
        verdict = "failed" if self.errors else "ok"
        print(f"design {'check' if self.check else 'sync'} {verdict}: {len(roots)} tree(s), {leaves} leaves, "
              f"{len(self.errors)} error(s), {len(self.warnings)} warning(s)")
        return 1 if self.errors else 0


def main(argv: list[str]) -> int:
    root, check = None, False
    args = list(argv)
    while args:
        arg = args.pop(0)
        if arg == "--check":
            check = True
        elif arg == "--root" and args:
            root = Path(args.pop(0))
        else:
            print(__doc__.strip().split("\n\n")[1], file=sys.stderr)
            return 2
    repo = (root or Path.cwd()).resolve()
    return Tree(repo, check).run()


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
